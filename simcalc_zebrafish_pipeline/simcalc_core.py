"""Only the SimCalc kernel and placement helpers used by the final highSNR model."""
from contextlib import contextmanager
from pathlib import Path
import sys
import numpy as np
from scipy.ndimage import gaussian_filter

sys.path.insert(0,str(Path(__file__).resolve().parent/'vendor/SimCalc'))
from simcalc import SimCalc

@contextmanager
def numpy_seed(seed):
    state = np.random.get_state()
    np.random.seed(seed)
    try:
        yield
    finally:
        np.random.set_state(state)

def uniform_centres(shape, count, spacing, rng):
    """Uniform placement with a scalar minimum distance, no spatial map."""
    if not count:
        return np.empty((0, 2), dtype=np.float32)
    centres, bins = [], {}
    for _ in range(max(1000, count * 100)):
        centre = rng.uniform(0, np.asarray(shape) - 1)
        key = tuple(np.floor(centre / spacing).astype(int))
        neighbours = [point for y in range(key[0] - 1, key[0] + 2)
                      for x in range(key[1] - 1, key[1] + 2)
                      for point in bins.get((y, x), ())]
        if neighbours and np.min(np.sum((np.asarray(neighbours) - centre)**2, axis=1)) < spacing**2:
            continue
        centres.append(centre)
        bins.setdefault(key, []).append(centre)
        if len(centres) == count:
            return np.asarray(centres, dtype=np.float32)
    raise ValueError(f'Could place only {len(centres)}/{count} cells; reduce density or spacing')

def _build_scene(p, seed, *, centres=None, tissue=None, emission_gain=None, surface=None,
                 cell_amplitudes=None):
    """Shared kernel engine; optional fields are generated by an extension."""
    height, width = map(int, p['shape_yx'])
    count = (int(round(height * width * p['density_per_10000_pixels'] / 10000))
             if centres is None else len(centres))
    if count >= 65535:
        raise ValueError('Too many cells for uint16 labels; reduce density')
    rng = np.random.default_rng(seed)
    if centres is None:
        centres = uniform_centres((height, width), count, p['min_spacing_px'], rng)
    sigma = p['sigma_px'] * np.clip(rng.lognormal(-p['size_cv']**2/2, p['size_cv'], count), .45, 2.)
    covariance = sigma**2 * rng.uniform(-p['eccentricity'], p['eccentricity'], count)
    amplitudes = rng.lognormal(-p['amplitude_cv']**2/2, p['amplitude_cv'], count)
    if cell_amplitudes is not None:
        amplitudes = np.asarray(cell_amplitudes, dtype=float)
        if amplitudes.shape != (count,) or not np.isfinite(amplitudes).all() or np.any(amplitudes < 0):
            raise ValueError('Cell amplitudes must be a nonnegative length-N vector')
    rings = rng.random(count) < p['ring_fraction']
    signal = np.zeros((height, width), dtype=np.float32)
    strength = np.zeros_like(signal)
    labels = np.zeros((height, width), dtype=np.uint16)
    square_side = max(height, width)
    for index, (centre, size, cov, amplitude, ring) in enumerate(
            zip(centres, sigma, covariance, amplitudes, rings)):
        radius = int(np.ceil(4 * size)) + 2
        origin = np.floor(centre).astype(int) - radius
        side = 2 * radius + 1
        model = SimCalc(h=side, N=1, T=1, StimCycles=1, dt=1)
        model.gen_spat_kernels(locs=(centre-origin)[None], sizes=np.array([size**2]),
                               covs=np.array([cov]), use_rings=bool(ring))
        # Match native square SimCalc's reflected optical boundary, then
        # crop the rectangular FOV. Do not blur through the square boundary.
        square_origin = np.maximum(origin, 0)
        square_end = np.minimum(origin + side, square_side)
        square_local = tuple(slice(a-o, b-o) for a, b, o in zip(square_origin, square_end, origin))
        kernel = gaussian_filter(model.spat_kernels[0][square_local], p['blur_px'])
        y0, x0 = np.maximum(origin, 0)
        y1, x1 = np.minimum(origin + side, (height, width))
        local = (slice(y0-origin[0], y1-origin[0]), slice(x0-origin[1], x1-origin[1]))
        target = (slice(y0, y1), slice(x0, x1))
        blurred_local = (slice(y0-square_origin[0], y1-square_origin[0]),
                         slice(x0-square_origin[1], x1-square_origin[1]))
        intensity = (kernel[blurred_local] * amplitude).astype(np.float32)
        mask = model.masks[0][local]
        if tissue is not None:
            intensity *= tissue[target]
            mask = mask & (tissue[target] >= .5)
        if emission_gain is not None:
            intensity *= emission_gain[target]
        signal[target] += intensity
        replace = mask & (intensity > strength[target])
        strength[target][replace] = intensity[replace]
        labels[target][replace] = index + 1
    side = max(height, width)
    with numpy_seed(seed + 2003):
        background = SimCalc(h=side, N=0, T=1, StimCycles=1, dt=1)
        background.gen_npil(eta=0, F0=1, nFilts=p['neuropil_filters'])
    neuropil = np.maximum(0, 1 + p['background_texture'] * (background.Bg_img - 1)) * p['background']
    if tissue is not None:
        neuropil[:height, :width] *= tissue
    if emission_gain is not None:
        neuropil[:height, :width] *= emission_gain
    if surface is not None:
        signal += surface
    return {'signal': signal, 'background_square': neuropil,
            'latent_fluorescence': (signal + neuropil[:height, :width]).astype(np.float32),
            'labels': labels, 'centres_yx': centres, 'sigma_px': sigma.astype(np.float32),
            'covariances': covariance.astype(np.float32),
            'amplitudes': amplitudes.astype(np.float32), 'rings': rings,
            'neuron_count': count}

def sample_head_centres(support, count, spacing, rng, density_weights=None):
    eligible = np.argwhere(support)
    if not len(eligible) or count < 1:
        raise ValueError("No tissue area is available for neuron placement")
    cumulative = None
    if density_weights is not None:
        weights = np.asarray(density_weights)[support]
        if not np.isfinite(weights).all() or np.any(weights < 0) or weights.sum() <= 0:
            raise ValueError("Neuron density weights must be finite, nonnegative and nonempty")
        cumulative = np.cumsum(weights, dtype=np.float64)
    centres, bins = [], {}
    for _ in range(max(1000, count * 150)):
        candidate = (int(rng.integers(len(eligible))) if cumulative is None else
                     int(np.searchsorted(cumulative, rng.random() * cumulative[-1], side='right')))
        centre = eligible[candidate].astype(float)
        centre += rng.uniform(-.45, .45, 2)
        key = tuple(np.floor(centre / spacing).astype(int))
        neighbours = [point for a in range(key[0] - 1, key[0] + 2)
                      for b in range(key[1] - 1, key[1] + 2)
                      for point in bins.get((a, b), ())]
        if neighbours and np.min(np.sum((np.asarray(neighbours) - centre) ** 2, axis=1)) < spacing ** 2:
            continue
        centres.append(centre)
        bins.setdefault(key, []).append(centre)
        if len(centres) == count:
            return np.asarray(centres, dtype=np.float32)
    raise RuntimeError(f"Could place only {len(centres)}/{count} head neurons; reduce density/spacing")

def inverse_warp_diagnostics(grid, shape):
    """Check the bilinear grid's Jacobian near all corners of every cell."""
    grid=np.asarray(grid)
    sy,sx=shape[0]/(grid.shape[1]-1),shape[1]/(grid.shape[2]-1)
    # Jacobian determinant of a bilinear mapping is affine within a cell;
    # checking all four corners also bounds the determinant in its interior.
    mins,maxs=[],[]
    for iy,ix in ((0,0),(0,1),(1,0),(1,1)):
        dy_y=(grid[0,1:,:]-grid[0,:-1,:])/sy
        dx_y=(grid[1,1:,:]-grid[1,:-1,:])/sy
        dy_x=(grid[0,:,1:]-grid[0,:,:-1])/sx
        dx_x=(grid[1,:,1:]-grid[1,:,:-1])/sx
        jac=(1+dy_y[:,ix:ix+grid.shape[2]-1])*(1+dx_x[iy:iy+grid.shape[1]-1,:]) \
            -dy_x[iy:iy+grid.shape[1]-1,:]*dx_y[:,ix:ix+grid.shape[2]-1]
        mins.append(float(jac.min()));maxs.append(float(jac.max()))
    return min(mins),max(maxs)
